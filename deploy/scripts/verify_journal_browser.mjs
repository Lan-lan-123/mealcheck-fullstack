// Verify the production UI against real APIs using only the caller's disposable account.
import { chromium, expect } from '../../frontend/node_modules/@playwright/test/index.mjs'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
let input = ''; for await (const chunk of process.stdin) input += chunk
const config = JSON.parse(input), checks = []
let passed = false
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await page.addInitScript(auth => {
    localStorage.setItem('mealcheck_token', auth.token)
    localStorage.setItem('mealcheck_user', JSON.stringify({ username: auth.username, displayName: auth.displayName, role: 'USER' }))
  }, config.auth)
  await page.goto(config.baseUrl + '/user/records')
  const meal = page.locator('.record-list .record').filter({ hasText: '青菜（部署验证）' })
  await expect(meal).toContainText('手动')
  await meal.getByRole('button', { name: '修改用餐信息' }).click()
  const edit = page.getByRole('dialog', { name: '修改用餐信息' })
  await edit.getByLabel('餐次', { exact: true }).selectOption('LUNCH')
  await edit.getByLabel('备注').fill('Synthetic production browser journal edit')
  await edit.getByRole('button', { name: '保存用餐记录' }).click()
  await expect(meal).toContainText('午餐')
  checks.push('production mobile metadata editor saves actual meal slot through the API')
  await expect(page.getByRole('button', { name: '撤销未吃标记' })).toBeVisible()
  checks.push('explicit not eaten status remains separate from unknown slots')
  await mkdir(config.output, { recursive: true })
  await page.screenshot({ path: path.join(config.output, 'journal-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.goto(config.baseUrl + '/user/goals')
  await expect(page.locator('.behavior-goal-list')).toContainText('每天记录 1 个餐次')
  await expect(page.getByRole('region', { name: '记录覆盖与执行情况' })).toContainText('已达标')
  await page.screenshot({ path: path.join(config.output, 'behavior-goals-mobile.png'), fullPage: true })
  checks.push('persisted behavior goal and real completion progress render on mobile')
  const goalPages = page.getByRole('navigation', { name: '行为目标分页' })
  await expect(goalPages).toContainText('共 106 条')
  await goalPages.getByRole('button', { name: '下一页' }).click()
  await expect(goalPages).toContainText('第 2 / 6 页')
  checks.push('production goal pagination loads the next page beyond the visible list')
  await page.goto(config.baseUrl + '/user/reports')
  await expect(page.getByRole('region', { name: '记录覆盖与执行情况' })).toContainText('跳过 0')
  await page.getByRole('button', { name: '打开导航菜单' }).click()
  await page.getByRole('button', { name: '行动计划', exact: true }).click()
  const plan = page.locator('.plan-list .record').filter({ hasText: 'Synthetic assistant plan' })
  await plan.getByRole('button', { name: '跳过', exact: true }).click()
  await expect(plan).toContainText('已跳过')
  await plan.getByRole('button', { name: '调整计划' }).click()
  await plan.getByLabel('执行备注').fill('Synthetic browser skip note')
  await plan.getByRole('button', { name: '保存调整' }).click()
  await expect(plan).toContainText('Synthetic browser skip note')
  await page.screenshot({ path: path.join(config.output, 'plans-mobile.png'), fullPage: true })
  checks.push('production plan skip and note adjustment persist through real APIs')
  await expect(page.getByRole('navigation', { name: '行动计划分页' })).toContainText('共 602 条')
  await page.getByRole('button', { name: '加入计划', exact: true }).click()
  await page.getByLabel('计划标题', { exact: true }).fill('Production continuous plan one')
  await page.getByLabel('具体行动').fill('Synthetic first manual action')
  await page.getByRole('button', { name: '保存行动计划' }).click()
  await page.getByRole('button', { name: '继续新增计划' }).click()
  await expect(page.getByLabel('具体行动')).toHaveValue('')
  await page.getByLabel('计划标题', { exact: true }).fill('Production continuous plan two')
  await page.getByLabel('具体行动').fill('Synthetic second manual action')
  await page.getByRole('button', { name: '保存行动计划' }).click()
  await expect(page.getByRole('button', { name: '继续新增计划' })).toBeEnabled()
  await expect(page.getByRole('navigation', { name: '行动计划分页' })).toContainText('共 604 条')
  checks.push('production manual plan form saves twice and refreshes paginated totals')
  await page.getByRole('button', { name: '打开导航菜单' }).click()
  await page.getByRole('button', { name: '我的周报', exact: true }).click()
  await expect(page.getByRole('region', { name: '记录覆盖与执行情况' })).toContainText('跳过 1')
  checks.push('returning to production report shows fresh plan execution')
  await page.getByRole('button', { name: '查看这份历史周报' }).click()
  const archive = page.getByRole('dialog', { name: '历史周报快照' })
  await expect(archive).toContainText('此报告已过期，内容不会自动改写')
  await page.screenshot({ path: path.join(config.output, 'archived-report-mobile.png'), fullPage: true })
  await archive.getByRole('button', { name: '关闭详情' }).click()
  checks.push('production stale report remains accessible as an original snapshot')
  await page.goto(config.baseUrl + '/user/overview')
  await page.locator('.assistant-fab').click()
  await page.getByPlaceholder('问问怎么吃更合适').fill('如何回顾午餐记录？')
  await page.getByRole('button', { name: '发送问题' }).click()
  await expect(page.getByRole('button', { name: '评价这条回答' })).toBeVisible({ timeout: 20_000 })
  await page.getByRole('button', { name: '评价这条回答' }).click()
  await page.getByLabel('是否有帮助').selectOption('HELPFUL')
  await page.getByRole('button', { name: '提交回答反馈' }).click()
  await expect(page.getByText('已提交反馈')).toBeVisible()
  checks.push('production assistant local fallback SSE and feedback work without real model calls')
  await page.screenshot({ path: path.join(config.output, 'assistant-feedback-mobile.png'), fullPage: true })
  passed = true
} finally {
  await browser.close(); await mkdir(config.output, { recursive: true })
  await writeFile(path.join(config.output, 'verification.json'), JSON.stringify({ passed, checks, limitations: ['Real AI quality, provider interoperability and provider billing are deferred.'] }, null, 2))
}
console.log(JSON.stringify({ passed, checks: checks.length }))
