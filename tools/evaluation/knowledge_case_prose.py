def compose(row, cases, section_count):
    sections = []
    kind = domain(row['topicIndex'])
    for phase in range(section_count):
        current = cases[phase % 3]
        other = cases[(phase + 1) % 3]
        heading, first, second = prose(kind, phase, row['title'], *current, *other)
        paragraphs = [first, second]
        # State the shared explanation once, followed by short, concrete applications.
        # Repeating a whole explanation once per case would inflate long articles.
        for index, (situation, action, limit) in enumerate(cases):
            other_situation, other_action, other_limit = cases[(index + 1) % 3]
            case_paragraphs = [
                f'假设案例：{situation}。可执行的第一步是{action}。需要特别留下的限制是“{limit}”。这几个信息分别回答眼前发生了什么、本人能做什么、哪些结论不能据此得到；不需要给食品再贴一个绝对好坏的标签。所描述的是判断方法，不是已发生的个人经历或产品实测结果。',
                f'把“{situation}”转成具体安排时，可先{action}，再看现场是否真的提供了相应条件。本例中，{limit}，因此不能只凭想法已经写下就默认结果成立。若供应方或本人补充了信息，应确认它回答的是原料、数量、操作还是实际选择，只修改与答复有关的判断，其他未知部分继续保留。',
                f'记录“{situation}”时，{action}可以作为本次处理经过，但是否真的做到要由实际事实支持。注释中保留“{limit}”，有助于避免后来只看数字而误读。可确认的数量写明对象和依据，无法确认的数值不补零；购买、计划和实际使用不相同，不能把同一食品在不同描述中重复计算。',
                f'条件对照：“{situation}”可{action}；“{other_situation}”可{other_action}。两者不能互相覆盖，因为前者有“{limit}”的边界，后者则要保留“{other_limit}”。对照重点是相关事实变了以后动作怎样变，不是评出哪个人更自律，也不由同类食品名称推定所有条件相同。',
                f'下次仍遇到“{situation}”时，可以预先为{action}准备所需信息与可用条件。若现场情况变了，先检查变化是否涉及“{limit}”这一限制，再决定原来的动作还适不适用。不能只是照抄上次选择；旧包装、旧照片、过去一次经验或原定时间，只能支持各自当时的情况，不能替代本次事实。',
                f'复盘“{situation}”时，可先问本人有没有实际做到{action}，再说明遇到的障碍。执行记录应保留“{limit}”这一边界，不把操作完成当成所有问题已经解决。若本次未食用或没有执行，就保留真实状态；下一步按实际条件调整，既不编造摄入，也不为达成应用目标要求额外进食、漏餐或补偿性运动。',
            ]
            paragraphs.append(case_paragraphs[phase])
        sections.append({'heading': heading, 'paragraphs': paragraphs})
    return {'sections': sections}
