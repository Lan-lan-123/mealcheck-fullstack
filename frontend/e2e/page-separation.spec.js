const foods = Array.from({ length: 10 }, (_, i) => ({ name: `食物 ${i + 1}`, category: 'vegetable' }))
const advice = '完整饮食建议。'.repeat(100) + '建议末尾仍然保留'
const meal = { id: 1, createdAt: '2026-09-30T12:00:00', score: 88, summary: '本次餐食结构均衡', foods, riskTags: ['蔬菜不足'], advice, categoryCounts: { vegetable: 10 } }
