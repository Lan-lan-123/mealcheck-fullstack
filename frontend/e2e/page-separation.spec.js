const trend = { days: 30, total: 8, averageScore: 88, dailyAverageScores: Array.from({ length: 30 }, (_, i) => ({ label: `日期 ${i + 1}`, value: 80 + i % 10 })), foodCounts: [{ label: '蔬菜', value: 10 }], riskTagCounts: [] }
const benchmark = { runId: 'run-1', status: 'COMPLETED', verdict: 'PASSED', mode: 'QUICK', completedCount: 10, caseCount: 10,
  judgedCount: 10, passedCount: 10, passRate: 1, intentMacroF1: .98, cases: [], datasetVersion: 'test', elapsedMs: 2000 }

async function fixture(page, role) {
  const errors = [], mutations = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(role => {
    localStorage.setItem('mealcheck_token', 'separation-test')
    localStorage.setItem('mealcheck_user', JSON.stringify({ username: 'demo', displayName: '测试账户', role }))
  }, role)
  let goal = { goalType: 'balanced', note: '', endDate: '' }
  await page.route('**/api/**', route => {
    const request = route.request(), url = new URL(request.url()), path = url.pathname
    if (!path.startsWith('/api/')) return route.continue()
    if (!['GET', 'HEAD'].includes(request.method())) mutations.push(path)
    const send = data => route.fulfill({ contentType: 'application/json', body: JSON.stringify(data) })
    if (path === '/api/profile/goals/current') {
      if (request.method() !== 'GET') goal = request.postDataJSON()
      return send(goal)
    }
    if (path === '/api/meals/analysis-requests') return send({ status: 'SUCCEEDED', result: { recordId: 1, evaluation: { score: 88, summary: meal.summary, riskTags: meal.riskTags }, recognition: { foods }, advice, references: [{ id: 1, title: '均衡搭配知识', score: .9, content: '知识片段原文完整保留' }] } })
    if (path === '/api/meals') return send({ content: [meal], totalPages: 1, totalElements: 1, page: 0 })
    if (path === '/api/reports/weekly/latest') return send(report)
    if (path === '/api/meals/trends') return send(trend)
    if (path === '/api/admin/dashboard') return send({ overview: { userCount: 12 }, operations: { activeUsers7d: 9, aiSuccessCount: 18 }, system: { aiMetrics: [{ operation: '餐食识别', calls: 20, successCount: 18, failureCount: 2, averageLatencyMs: 300 }] },
      ragEvaluation: { searches24h: 42, noAnswerSearches24h: 3 }, nonFoodUploadAlerts: [{ username: '预警用户', count: 5, limit: 3, windowMinutes: 10 }],
      assistantStats: { questionCount: 55, questionsByUser: Array.from({ length: 20 }, (_, i) => ({ label: `用户 ${i + 1}`, value: 20 - i })) } })
    if (path === '/api/health') return send({ status: 'UP', databaseReachable: true, redisReachable: true, uploadDirectoryWritable: true })
    if (path === '/api/admin/assistant/evaluation') return send(benchmark)
    if (path === '/api/admin/assistant/evaluation/history') return send({ runs: [benchmark] })
    if (path === '/api/admin/assistant/evaluation/candidates') return send({ candidates: [] })
    if (path === '/api/admin/knowledge/evaluation') return send({ caseCount: 10, hitAt3: .9, cases: [] })
    if (path === '/api/assistant/conversations') return send([])
    return send(null)
  })
  await page.goto('/')
  return { errors, mutations }
}

